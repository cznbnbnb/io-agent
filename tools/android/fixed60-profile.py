"""Validate the existing fixed60 research input; generate metadata/code, never firmware."""
import hashlib,json,pathlib,sys,zipfile
ROOT=pathlib.Path(__file__).resolve().parents[2]
APP=ROOT/'rebuild/android-app'
BASE=ROOT/'rebuild/phase1/device-private/stock-firmware-1.0.5.5'
SOURCE=BASE/'Strix-OS-1.0.5.5-original.zip'
CANDIDATE=BASE/'suggestion60-candidate/StrixOS-1.0.5.5-SUGGEST60-OFFLINE-01-UNFLASHED.zip'
ZIP_SHA='fcbc2d80bca5e64a2e1b1513c63bc0fe4527a85efe2751093bdc6235f8171cd9'
SOURCE_SHA='2927917f976ef3c9b183253e2342a7a0c85a3e454e973876100f3158da5ec367'
AP_SHA='657db3c8a91f82c1fd8078d8c41d25a57321294ebdaf4071beb412aaffe3698f'
ORIGINAL_AP_SHA='b3d6d9d7a4ece97e1dbaa64fc080eb5db8a5f7c9fecf340888ebb97a9112cc6c'
PATCHES=[(0x3f66b0,'41f28831','4ef66021'),(0x3f66ba,'41f28833','4ef66023'),(0x3ff028,'41f28831','4ef66021'),(0x3ff030,'4ff4fa51','4ef66021')]
sha=lambda b:hashlib.sha256(b).hexdigest()
canonical=lambda v:json.dumps(v,ensure_ascii=False,sort_keys=True,separators=(',',':')).encode()
candidate=CANDIDATE.read_bytes();source=SOURCE.read_bytes()
if len(candidate)!=8735334 or sha(candidate)!=ZIP_SHA or sha(source)!=SOURCE_SHA:raise ValueError('Reviewed ZIP source identity mismatch')
with zipfile.ZipFile(SOURCE) as old,zipfile.ZipFile(CANDIDATE) as new:
    names=new.namelist()
    if len(names)!=16 or len(set(names))!=16 or names!=old.namelist():raise ValueError('Firmware member set/order differs')
    manifest=json.loads(new.read('OtaFileInfo.json'));original_manifest=json.loads(old.read('OtaFileInfo.json'))
    if len(manifest)!=15 or {r['Name'] for r in manifest}!=set(names)-{'OtaFileInfo.json'}:raise ValueError('Firmware manifest membership')
    rows=[];total=0
    for name in names:
        if '/' in name or '\\' in name or name in {'.','..'}:raise ValueError('Unexpected member path')
        data=new.read(name);baseline=old.read(name);total+=len(data)
        if name=='nuttx_ap.bin':
            if len(data)!=7208648 or sha(data)!=AP_SHA or sha(baseline)!=ORIGINAL_AP_SHA:raise ValueError('AP identity')
            reversed_ap=bytearray(data)
            for offset,before,after in PATCHES:
                if data[offset:offset+4]!=bytes.fromhex(after) or baseline[offset:offset+4]!=bytes.fromhex(before):raise ValueError('Instruction pin')
                reversed_ap[offset:offset+4]=bytes.fromhex(before)
            if bytes(reversed_ap)!=baseline:raise ValueError('AP changed outside four instructions')
        elif name!='OtaFileInfo.json' and data!=baseline:raise ValueError('Non-AP payload changed')
        if name!='OtaFileInfo.json':
            entry=next(r for r in manifest if r['Name']==name)
            if set(entry)!={'Name','Size','Md5','BurnMode','BurnAddr','BurnPath'} or entry['Size']!=len(data) or entry['Md5']!=hashlib.md5(data).hexdigest():raise ValueError('Manifest payload mismatch')
        rows.append(dict(name=name,size=len(data),sha256=sha(data),md5=hashlib.md5(data).hexdigest(),source_sha256=sha(baseline)))
    reversed_manifest=json.loads(json.dumps(manifest));next(r for r in reversed_manifest if r['Name']=='nuttx_ap.bin')['Md5']=next(r for r in original_manifest if r['Name']=='nuttx_ap.bin')['Md5']
    if reversed_manifest!=original_manifest:raise ValueError('Manifest changed beyond AP MD5')
    original_ap_md5=next(r for r in original_manifest if r['Name']=='nuttx_ap.bin')['Md5']
profile=dict(schema=1,candidate='SUGGEST60-OFFLINE-01',firmware='1.0.5.5',wire_version='Strix OS 1.0.5.5',zip_bytes=len(candidate),zip_sha256=ZIP_SHA,source_zip_sha256=SOURCE_SHA,ap_bytes=7208648,ap_sha256=AP_SHA,source_ap_sha256=ORIGINAL_AP_SHA,expanded_bytes=total,manifest_original_canonical_sha256=sha(canonical(original_manifest)),source_ap_md5=original_ap_md5,members=rows,patches=[dict(offset=o,before=b,after=a) for o,b,a in PATCHES],firmware_written=False,device_io=False,installation_verified=False)
pins=',\n'.join('  '+json.dumps(f"{r['name']} {r['size']} {r['sha256']}") for r in rows)
source_code=f'''package com.turboio.addon;
// Generated by tools/android/fixed60-profile.py from both pinned research ZIPs.
// Metadata only; no firmware bytes and no device/network operations.
final class Fixed60Profile {{
 static final String ID="SUGGEST60-OFFLINE-01",VERSION="Strix OS 1.0.5.5";
 static final String ZIP_SHA="{ZIP_SHA}",AP_SHA="{AP_SHA}",SOURCE_AP_SHA="{ORIGINAL_AP_SHA}";
 static final String ORIGINAL_MANIFEST_SHA="{profile['manifest_original_canonical_sha256']}",SOURCE_AP_MD5="{original_ap_md5}";
 static final int ZIP_SIZE=8735334,AP_SIZE=7208648,EXPANDED_SIZE={total};
 static final String[] PINS={{
{pins}}};
 static final int[] PATCH_OFFSETS={{0x3f66b0,0x3f66ba,0x3ff028,0x3ff030}};
 static final String[] BEFORE={{"41f28831","41f28833","41f28831","4ff4fa51"}},AFTER={{"4ef66021","4ef66023","4ef66021","4ef66021"}};
}}
'''
outputs={APP/'fixed60-profile.json':json.dumps(profile,ensure_ascii=False,indent=2)+'\n',APP/'src/com/turboio/addon/Fixed60Profile.java':source_code}
for file,text in outputs.items():
    if '--check' in sys.argv:
        if file.read_text(encoding='utf-8')!=text:raise ValueError('Generated fixed60 profile differs: '+file.name)
    else:
        if file.exists():raise ValueError('Existing profile is not overwritten; inspect/check it')
        file.write_text(text,encoding='utf-8')
print(json.dumps(dict(candidate=profile['candidate'],firmware=profile['firmware'],members=len(rows),expanded_bytes=total,non_ap_payloads_unchanged=14,ap_changed_bytes=16,device_io=False)))
